import assert from 'node:assert/strict';
import { Webhook } from 'standardwebhooks';
import { verifyWhopWebhook } from '../supabase/functions/_shared/whop-verification.ts';
import { normalizeWhopEvent, serverPlanMap } from '../supabase/functions/_shared/whop-events.ts';
import { readFileSync } from 'node:fs';

const secret = 'ws_test_hashibot_official_contract';
const encoded = Buffer.from(secret, 'utf8').toString('base64');
const payload = JSON.stringify({ id:'evt_1', type:'membership.activated', timestamp:new Date().toISOString(), api_version:'v1', api_version_date:'2026-09-11', data:{ id:'mem_1', user_id:'user_1', plan_id:'plan_vip', product_id:'prod_1', status:'active', current_period_end:'2026-10-14T00:00:00Z', cancel_at_period_end:false, created_at:'2026-09-14T00:00:00Z' } });
const timestamp = new Date();
const headers = new Headers({ 'webhook-id':'msg_1', 'webhook-timestamp':String(Math.floor(timestamp.getTime()/1000)), 'webhook-signature':new Webhook(encoded).sign('msg_1', timestamp, payload) });
assert.equal(verifyWhopWebhook(payload, headers, secret).verified, true);
assert.equal(verifyWhopWebhook(payload, new Headers(), secret).verified, false);
const invalid = new Headers(headers); invalid.set('webhook-signature','v1,invalid');
assert.equal(verifyWhopWebhook(payload, invalid, secret).verified, false);
const staleAt = new Date(Date.now()-301_000), stale = new Headers({ 'webhook-id':'old', 'webhook-timestamp':String(Math.floor(staleAt.getTime()/1000)), 'webhook-signature':new Webhook(encoded).sign('old', staleAt, payload) });
assert.equal(verifyWhopWebhook(payload, stale, secret).verified, false);
assert.equal(verifyWhopWebhook(payload, headers, undefined).verified, false);
const verified = verifyWhopWebhook(payload, headers, secret); assert.ok(verified.verified);
const normalized = normalizeWhopEvent(verified.event);
assert.deepEqual([normalized.eventId,normalized.membershipId,normalized.planId,normalized.productId,normalized.providerCustomerId],['evt_1','mem_1','plan_vip','prod_1','user_1']);
const map = serverPlanMap(name => name==='WHOP_PLAN_VIP_SIGNALS'?'plan_vip':undefined);
assert.equal(map.get('plan_vip'),'crypto_signal_room'); assert.equal(map.get('wrong'),undefined);
const sql = readFileSync('supabase/migrations/20260914210000_whop_lifecycle_processing.sql','utf8');
const endpoint = readFileSync('supabase/functions/whop-webhook/index.ts','utf8');
assert.match(sql,/ON CONFLICT\(provider,provider_event_id\) DO NOTHING/);
assert.match(sql,/IGNORED_UNKNOWN_PLAN/); assert.match(sql,/membership\.cancel_at_period_end_changed/);
assert.match(sql,/membership\.deactivated/); assert.match(sql,/payment\.pending','payment\.failed/);
assert.match(sql,/refund\.created/); assert.match(sql,/dispute\.created/);
assert.match(endpoint,/WHOP_API_KEY/); assert.match(endpoint,/reconcileWhopObject/);
assert.doesNotMatch(readFileSync('src/pages/public/VipComplete.tsx','utf8'),/success=true|paid=true|searchParams/);
console.log('Whop backend readiness checks passed');
